# EXPERIMENT 2: Task-Type One-Hot Diagnostic
# ============================================================
def experiment_onehot_diagnostic(df, handcrafted_cols):
    """How much does knowing the task type help vs. features alone?"""
    print("\n" + "="*70)
    print("EXPERIMENT 2: Task-Type One-Hot Diagnostic")
    print("="*70)
    print("Does the model just memorize 'Snake is hard' or use grid features?")
    
    target = 'difficulty'
    
    # Stratified split (same as original)
    np.random.seed(42)
    train_idx, test_idx = [], []
    for task_name, group in df.groupby('task_name'):
        indices = group.index.values.copy()
        np.random.shuffle(indices)
        n_train = max(1, int(len(indices) * 0.75))
        train_idx.extend(indices[:n_train])
        test_idx.extend(indices[n_train:])
    
    y_train = df.loc[train_idx, target].values
    y_test = df.loc[test_idx, target].values
    
    results = {}
    
    # Model A: One-hot only (task type as the only feature)
    enc = OneHotEncoder(sparse_output=False)
    X_onehot_train = enc.fit_transform(df.loc[train_idx, ['task_name']])
    X_onehot_test = enc.transform(df.loc[test_idx, ['task_name']])
    
    model_a = Ridge(alpha=1.0)
    model_a.fit(X_onehot_train, y_train)
    pred_a = model_a.predict(X_onehot_test)
    results['one_hot_only'] = eval_metrics(y_test, pred_a)
    
    # Model B: Hand-crafted features only
    scaler = StandardScaler()
    X_hc_train = scaler.fit_transform(df.loc[train_idx, handcrafted_cols].values)
    X_hc_test = scaler.transform(df.loc[test_idx, handcrafted_cols].values)
    
    model_b = GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42)
    model_b.fit(X_hc_train, y_train)
    pred_b = model_b.predict(X_hc_test)
    results['features_only'] = eval_metrics(y_test, pred_b)
    
    # Model C: Features + one-hot (should be upper bound)
    X_combined_train = np.hstack([X_hc_train, X_onehot_train])
    X_combined_test = np.hstack([X_hc_test, X_onehot_test])
    
    model_c = GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42)
    model_c.fit(X_combined_train, y_train)
    pred_c = model_c.predict(X_combined_test)
    results['features_plus_onehot'] = eval_metrics(y_test, pred_c)
    
    # Model D: Features only, but remove reward-type heuristic features (these encode task type!)
    non_reward_cols = [c for c in handcrafted_cols if not c.startswith('reward_')]
    X_norw_train = scaler.fit_transform(df.loc[train_idx, non_reward_cols].values)
    X_norw_test = scaler.transform(df.loc[test_idx, non_reward_cols].values)
    
    model_d = GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42)
    model_d.fit(X_norw_train, y_train)
    pred_d = model_d.predict(X_norw_test)
    results['features_no_reward_type'] = eval_metrics(y_test, pred_d)
    
    print(f"\n{'Model':<30} {'Spearman ρ':>12} {'R²':>8} {'MSE':>8}")
    print("-" * 62)
    for name, m in results.items():
        print(f"{name:<30} {m['spearman_rho']:>12.4f} {m['r2']:>8.4f} {m['mse']:>8.4f}")
    
    print("\nInterpretation:")
    if results['one_hot_only']['spearman_rho'] > results['features_only']['spearman_rho'] - 0.05:
        print("  ⚠ One-hot is competitive with features → model may rely on task-type memorization")
    else:
        print("  ✓ Features beat one-hot → model uses grid structure beyond task type")
    
    return results


