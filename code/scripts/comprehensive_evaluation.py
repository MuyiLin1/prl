# EXPERIMENT 6: Per-Task Within-Task Prediction
# ============================================================
def experiment_within_task(df, handcrafted_cols):
    """Can we predict difficulty variation WITHIN a single task type?"""
    print("\n" + "="*70)
    print("EXPERIMENT 6: Within-Task Prediction")
    print("="*70)
    print("Does difficulty vary per-seed and can features predict it?")
    
    target = 'difficulty'
    richer = compute_richer_features(df)
    all_features = pd.concat([df[handcrafted_cols], richer], axis=1)
    
    tasks = df['task_name'].unique()
    
    print(f"\n{'Task':<22} {'Std(diff)':>10} {'N unique':>10} {'Corr w/ ecc':>12}")
    print("-" * 58)
    
    for task in sorted(tasks):
        mask = df['task_name'] == task
        diffs = df.loc[mask, target].values
        ecc = df.loc[mask, 'graph_start_eccentricity'].values
        
        n_unique = len(np.unique(np.round(diffs, 4)))
        std = np.std(diffs)
        
        if std > 0.01 and np.std(ecc) > 0.01:
            corr, _ = spearmanr(diffs, ecc)
        else:
            corr = 0.0
        
        print(f"{task:<22} {std:>10.4f} {n_unique:>10} {corr:>12.4f}")


