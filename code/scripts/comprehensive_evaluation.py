# EXPERIMENT 1: Leave-One-Task-Out (LOTO)
# ============================================================
def experiment_loto(df, handcrafted_cols, raw_grid_cols):
    """Leave-one-task-out: train on N-1 tasks, predict the held-out task."""
    print("\n" + "="*70)
    print("EXPERIMENT 1: Leave-One-Task-Out (LOTO)")
    print("="*70)
    print("Can the model generalize to entirely unseen task types?")
    
    tasks = df['task_name'].unique()
    target = 'difficulty'
    
    results_per_task = {}
    
    for held_out in tasks:
        train_df = df[df['task_name'] != held_out]
        test_df = df[df['task_name'] == held_out]
        
        X_train = train_df[handcrafted_cols].values
        y_train = train_df[target].values
        X_test = test_df[handcrafted_cols].values
        y_test = test_df[target].values
        
        scaler = StandardScaler()
        X_train_s = scaler.fit_transform(X_train)
        X_test_s = scaler.transform(X_test)
        
        model = GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42)
        model.fit(X_train_s, y_train)
        y_pred = model.predict(X_test_s)
        
        metrics = eval_metrics(y_test, y_pred)
        metrics['true_mean'] = y_test.mean()
        metrics['pred_mean'] = y_pred.mean()
        results_per_task[held_out] = metrics
    
    # Print results
    print(f"\n{'Task Held Out':<22} {'True Mean':>10} {'Pred Mean':>10} {'MSE':>8} {'Spearman':>10}")
    print("-" * 65)
    
    all_spearman = []
    all_mse = []
    for task, m in sorted(results_per_task.items()):
        sr = m['spearman_rho']
        all_spearman.append(sr if not np.isnan(sr) else 0)
        all_mse.append(m['mse'])
        print(f"{task:<22} {m['true_mean']:>10.3f} {m['pred_mean']:>10.3f} {m['mse']:>8.4f} {sr:>10.4f}")
    
    print(f"\n  Mean LOTO Spearman ρ: {np.mean(all_spearman):.4f}")
    print(f"  Mean LOTO MSE:        {np.mean(all_mse):.4f}")
    
    # Also compute aggregate: pool all LOTO predictions
    all_true, all_pred = [], []
    for held_out in tasks:
        train_df = df[df['task_name'] != held_out]
        test_df = df[df['task_name'] == held_out]
        X_train = train_df[handcrafted_cols].values
        y_train = train_df[target].values
        X_test = test_df[handcrafted_cols].values
        y_test = test_df[target].values
        scaler = StandardScaler()
        X_train_s = scaler.fit_transform(X_train)
        X_test_s = scaler.transform(X_test)
        model = GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42)
        model.fit(X_train_s, y_train)
        y_pred = model.predict(X_test_s)
        all_true.extend(y_test)
        all_pred.extend(y_pred)
    
    pooled = eval_metrics(np.array(all_true), np.array(all_pred))
    print(f"\n  Pooled LOTO (all predictions): Spearman ρ = {pooled['spearman_rho']:.4f}, R² = {pooled['r2']:.4f}")
    
    return results_per_task, pooled


