# EXPERIMENT 5: LOTO with Richer Features + Best Model
# ============================================================
def experiment_loto_enhanced(df, handcrafted_cols):
    """LOTO with the best feature set and model from other experiments."""
    print("\n" + "="*70)
    print("EXPERIMENT 5: Enhanced LOTO (richer features + tuned model)")
    print("="*70)
    
    target = 'difficulty'
    richer = compute_richer_features(df)
    richer_cols = richer.columns.tolist()
    all_cols = handcrafted_cols + richer_cols
    X_all = pd.concat([df[handcrafted_cols], richer], axis=1)
    
    tasks = df['task_name'].unique()
    
    # Also try: features WITHOUT reward-type (pure structural prediction)
    structural_cols = [c for c in handcrafted_cols if not c.startswith('reward_')] + richer_cols
    X_structural = pd.concat([df[[c for c in handcrafted_cols if not c.startswith('reward_')]], richer], axis=1)
    
    configs = {
        'GBR + all features': (X_all, GradientBoostingRegressor(n_estimators=150, max_depth=4, random_state=42)),
        'RF + all features': (X_all, RandomForestRegressor(n_estimators=200, max_depth=5, random_state=42)),
        'GBR + structural only': (X_structural, GradientBoostingRegressor(n_estimators=150, max_depth=4, random_state=42)),
    }
    
    for config_name, (X_data, model_template) in configs.items():
        print(f"\n  Config: {config_name}")
        all_true, all_pred = [], []
        
        for held_out in tasks:
            train_mask = df['task_name'] != held_out
            test_mask = df['task_name'] == held_out
            
            X_train = X_data[train_mask].values
            y_train = df.loc[train_mask, target].values
            X_test = X_data[test_mask].values
            y_test = df.loc[test_mask, target].values
            
            scaler = StandardScaler()
            X_train_s = scaler.fit_transform(X_train)
            X_test_s = scaler.transform(X_test)
            
            from sklearn.base import clone
            model = clone(model_template)
            model.fit(X_train_s, y_train)
            y_pred = model.predict(X_test_s)
            
            all_true.extend(y_test)
            all_pred.extend(y_pred)
        
        pooled = eval_metrics(np.array(all_true), np.array(all_pred))
        print(f"    Pooled LOTO: Spearman ρ = {pooled['spearman_rho']:.4f}, R² = {pooled['r2']:.4f}, MSE = {pooled['mse']:.4f}")


