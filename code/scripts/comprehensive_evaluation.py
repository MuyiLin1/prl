# EXPERIMENT 4: Multiple Model Comparison
# ============================================================
def experiment_model_comparison(df, handcrafted_cols):
    """Compare multiple model types on the same features."""
    print("\n" + "="*70)
    print("EXPERIMENT 4: Model Type Comparison")
    print("="*70)
    
    target = 'difficulty'
    
    # Stratified split
    np.random.seed(42)
    train_idx, test_idx = [], []
    for task_name, group in df.groupby('task_name'):
        indices = group.index.values.copy()
        np.random.shuffle(indices)
        n_train = max(1, int(len(indices) * 0.75))
        train_idx.extend(indices[:n_train])
        test_idx.extend(indices[n_train:])
    
    y_train = df.loc[train_idx, target].values
    y_test = df.loc[test_idx, target].values
    
    scaler = StandardScaler()
    X_train = scaler.fit_transform(df.loc[train_idx, handcrafted_cols].values)
    X_test = scaler.transform(df.loc[test_idx, handcrafted_cols].values)
    
    models = {
        'Ridge (α=1.0)': Ridge(alpha=1.0),
        'Ridge (α=10)': Ridge(alpha=10.0),
        'Lasso (α=0.01)': Lasso(alpha=0.01),
        'SVR (RBF)': SVR(kernel='rbf', C=1.0),
        'SVR (RBF, C=10)': SVR(kernel='rbf', C=10.0),
        'RF (100, d=3)': RandomForestRegressor(n_estimators=100, max_depth=3, random_state=42),
        'RF (200, d=5)': RandomForestRegressor(n_estimators=200, max_depth=5, random_state=42),
        'RF (300, d=7)': RandomForestRegressor(n_estimators=300, max_depth=7, random_state=42),
        'GBR (100, d=3)': GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42),
        'GBR (200, d=4)': GradientBoostingRegressor(n_estimators=200, max_depth=4, random_state=42),
        'GBR (300, d=5)': GradientBoostingRegressor(n_estimators=300, max_depth=5, random_state=42),
    }
    
    results = {}
    print(f"\n{'Model':<25} {'Spearman ρ':>12} {'Pearson r':>12} {'R²':>8} {'MSE':>8}")
    print("-" * 70)
    
    for name, model in models.items():
        model.fit(X_train, y_train)
        pred = model.predict(X_test)
        m = eval_metrics(y_test, pred)
        results[name] = m
        print(f"{name:<25} {m['spearman_rho']:>12.4f} {m['pearson_r']:>12.4f} {m['r2']:>8.4f} {m['mse']:>8.4f}")
    
    return results


