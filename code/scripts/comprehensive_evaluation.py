# EXPERIMENT 3: Richer Features
# ============================================================
def compute_richer_features(df):
    """Derive additional features from existing columns."""
    richer = pd.DataFrame(index=df.index)
    
    # Ratios and interactions
    richer['deadend_fraction'] = df['graph_num_deadends'] / df['graph_num_free_cells'].clip(lower=1)
    richer['corridor_fraction'] = df['graph_num_corridor_cells'] / df['graph_num_free_cells'].clip(lower=1)
    richer['branch_fraction'] = df['graph_num_branch_cells'] / df['graph_num_free_cells'].clip(lower=1)
    richer['edge_to_node_ratio'] = df['graph_num_edges'] / df['graph_num_free_cells'].clip(lower=1)
    richer['diameter_to_area'] = df['graph_diameter'] / df['grid_area'].clip(lower=1)
    richer['eccentricity_to_diameter'] = df['graph_start_eccentricity'] / df['graph_diameter'].clip(lower=1)
    richer['mean_dist_to_diameter'] = df['graph_mean_pair_distance'] / df['graph_diameter'].clip(lower=1)
    
    # Spectral gap (algebraic connectivity) — lambda_1 is the Fiedler value
    richer['spectral_gap'] = df['spectral_lambda_1']
    richer['spectral_ratio_1_2'] = df['spectral_lambda_1'] / df['spectral_lambda_2'].clip(lower=1e-6)
    
    # Complexity indicators
    richer['markers_per_free_cell'] = df['graph_num_markers'] / df['graph_num_free_cells'].clip(lower=1)
    richer['degree_variance'] = (df['graph_max_degree'] - df['graph_min_degree'])
    richer['compactness'] = df['graph_num_free_cells'] / df['grid_area'].clip(lower=1)
    
    # Grid shape
    richer['aspect_ratio'] = df['grid_width'] / df['grid_height'].clip(lower=1)
    
    # Interaction: eccentricity × markers (harder if far to travel AND things to collect)
    richer['ecc_x_markers'] = df['graph_start_eccentricity'] * df['graph_num_markers']
    richer['ecc_x_components'] = df['graph_start_eccentricity'] * df['graph_num_components']
    
    return richer


def experiment_richer_features(df, handcrafted_cols):
    """Test if richer derived features improve prediction."""
    print("\n" + "="*70)
    print("EXPERIMENT 3: Richer Derived Features")
    print("="*70)
    
    target = 'difficulty'
    richer = compute_richer_features(df)
    richer_cols = richer.columns.tolist()
    
    # Stratified split
    np.random.seed(42)
    train_idx, test_idx = [], []
    for task_name, group in df.groupby('task_name'):
        indices = group.index.values.copy()
        np.random.shuffle(indices)
        n_train = max(1, int(len(indices) * 0.75))
        train_idx.extend(indices[:n_train])
        test_idx.extend(indices[n_train:])
    
    y_train = df.loc[train_idx, target].values
    y_test = df.loc[test_idx, target].values
    
    results = {}
    
    # Baseline: original features
    scaler = StandardScaler()
    X_train = scaler.fit_transform(df.loc[train_idx, handcrafted_cols].values)
    X_test = scaler.transform(df.loc[test_idx, handcrafted_cols].values)
    
    model = GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42)
    model.fit(X_train, y_train)
    results['baseline_32_features'] = eval_metrics(y_test, model.predict(X_test))
    
    # Richer only
    X_rich_train = scaler.fit_transform(richer.loc[train_idx].values)
    X_rich_test = scaler.transform(richer.loc[test_idx].values)
    
    model2 = GradientBoostingRegressor(n_estimators=100, max_depth=3, random_state=42)
    model2.fit(X_rich_train, y_train)
    results['richer_only'] = eval_metrics(y_test, model2.predict(X_rich_test))
    
    # Combined: original + richer
    all_cols = handcrafted_cols + richer_cols
    X_all = pd.concat([df[handcrafted_cols], richer], axis=1)
    X_all_train = scaler.fit_transform(X_all.loc[train_idx].values)
    X_all_test = scaler.transform(X_all.loc[test_idx].values)
    
    model3 = GradientBoostingRegressor(n_estimators=150, max_depth=4, random_state=42)
    model3.fit(X_all_train, y_train)
    pred3 = model3.predict(X_all_test)
    results['combined_48_features'] = eval_metrics(y_test, pred3)
    
    # RF on combined for feature importance
    model_rf = RandomForestRegressor(n_estimators=200, max_depth=5, random_state=42)
    model_rf.fit(X_all_train, y_train)
    results['combined_RF'] = eval_metrics(y_test, model_rf.predict(X_all_test))
    
    print(f"\n{'Model':<30} {'Spearman ρ':>12} {'R²':>8} {'MSE':>8}")
    print("-" * 62)
    for name, m in results.items():
        print(f"{name:<30} {m['spearman_rho']:>12.4f} {m['r2']:>8.4f} {m['mse']:>8.4f}")
    
    # Feature importance from RF
    print("\n  Top 15 features (RF on combined set):")
    importances = model_rf.feature_importances_
    top_idx = np.argsort(importances)[::-1][:15]
    for i in top_idx:
        print(f"    {all_cols[i]:35s} {importances[i]:.4f}")
    
    return results, richer_cols


